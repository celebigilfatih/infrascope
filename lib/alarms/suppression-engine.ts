/**
 * Alarm Suppression Engine
 * 
 * Filters noisy infrastructure events to prevent false-positive alerts,
 * while still allowing real anomalies to be detected.
 * 
 * Supports suppression rules for:
 * - VMware automation events (vMotion, snapshots, backups)
 * - Backup tool events (Veeam, etc.)
 * - Service account activity
 * - Time-based maintenance windows
 * - Device/port-based suppression
 */

export interface SuppressionEvent {
  // Core identifiers
  userName?: string;
  vmName?: string;
  hostName?: string;
  deviceName?: string;
  portName?: string;
  
  // Event metadata
  eventType?: string;
  message?: string;
  source?: string;
  alarmCode?: string;
  
  // Timestamp for time-based rules
  timestamp?: string | Date;
}

export interface SuppressionRule {
  id: string;
  name: string;
  description?: string;
  
  // Which alarm codes this rule applies to (empty = all)
  alarmCodes: string[];
  
  // Event type matching (empty = all)
  eventTypes?: string[];
  
  // Keyword matching (case-insensitive)
  keywords?: string[];
  
  // Field-based matching
  field?: 'userName' | 'vmName' | 'hostName' | 'deviceName' | 'portName';
  fieldValues?: string[];
  
  // Time-based suppression
  timeWindow?: {
    startHour: number;   // 0-23
    endHour: number;     // 0-23
    days?: number[];     // 0=Sunday, 1=Monday, ..., 6=Saturday (empty = all days)
  };
  
  // Enable/disable
  enabled: boolean;
  
  // Reason for suppression (logged for audit)
  reason?: string;
}

