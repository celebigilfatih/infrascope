/* eslint-disable @typescript-eslint/no-require-imports -- Standalone regression runner. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const filename = require('node:path').resolve('lib/topology/presentation.ts');
assert.ok(fs.existsSync(filename), 'Visual topology presentation model must exist');
const compiled = ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const loaded = new Module(filename, module); loaded._compile(compiled, filename);
const { suggestPresentation, validatePresentation, projectPresentation, arrangePresentation, movePresentationBuilding, removePresentationSection } = loaded.exports;
const buildings = ['hub', 'a', 'b', 'c', 'd', 'isolated'].map(id => ({ id, name: id }));
const links = [['hub','a'], ['a','b'], ['b','hub'], ['hub','c'], ['c','d'], ['d','hub']].map(([sourceBuildingId,destBuildingId], index) => ({ id: `link-${index}`, sourceBuildingId,destBuildingId }));
const original = JSON.stringify({ buildings, links });
const suggested = suggestPresentation(buildings, links);
assert.deepEqual(suggested.backboneIds, ['hub']);
assert.deepEqual(suggested.sections.map(s => s.buildingIds), [['a','b'],['c','d']]);
assert.deepEqual(suggestPresentation([...buildings].reverse(), [...links].reverse()), suggested, 'Suggestion is stable under input ordering');
assert.equal(JSON.stringify({ buildings, links }), original, 'Suggestions cannot change inventory');
assert.equal(validatePresentation(suggested, new Set(buildings.map(b => b.id))), null);
assert.match(validatePresentation({ ...suggested, backboneIds: ['hub','a'] }, new Set(buildings.map(b => b.id))), /birden fazla/);
assert.match(validatePresentation({ ...suggested, backboneIds: ['missing'] }, new Set(buildings.map(b => b.id))), /bulunamadı/);
assert.match(validatePresentation({ ...suggested, positions: { summary: { x: { x: NaN, y: 1 } } } }, new Set(buildings.map(b => b.id))), /konum/);
const projected = projectPresentation(suggested, buildings, links, 'summary');
assert.equal(projected.nodes.length, 4, 'Backbone, two sections and isolated building are all represented');
assert.deepEqual(projected.unplacedIds, ['isolated']);
assert.equal(projected.edges.length, 2);
assert.deepEqual(projected.edges.map(e => e.linkIds.length), [2,2]);
assert.equal(projected.internalLinkCount, 2, 'Internal physical links are counted rather than lost');
const expanded = projectPresentation(suggested, buildings, links, `section:${suggested.sections[0].id}`);
assert.deepEqual(expanded.nodes.filter(n => n.kind === 'building').map(n => n.buildingId).sort(), ['a','b','hub']);
assert.equal(expanded.edges.flatMap(e => e.linkIds).length, 3);
const full = projectPresentation(suggested, buildings, links, 'all');
assert.equal(full.nodes.length, 6); assert.equal(full.edges.flatMap(e => e.linkIds).length, 6);
const moved = movePresentationBuilding(suggested, 'a', suggested.sections[1].id);
assert.deepEqual(moved.sections[0].buildingIds, ['b']); assert.deepEqual(moved.sections[1].buildingIds, ['c','d','a']);
assert.equal(validatePresentation(moved, new Set(buildings.map(b => b.id))), null);
assert.deepEqual(removePresentationSection(suggested, suggested.sections[0].id).backboneIds, ['hub','a','b']);
const positions = arrangePresentation(full.nodes.map(n => n.id), full.edges);
const star=arrangePresentation(['hub','left','right'],[{source:'hub',target:'left'},{source:'hub',target:'right'}]);
assert.equal(star.left.x,star.right.x,'Summary branches share a column so a long edge cannot pass through another section card');
assert.notEqual(star.left.y,star.right.y);
const fanIds=['center',...Array.from({length:7},(_,i)=>`peer-${i}`)];
const fan=arrangePresentation(fanIds,fanIds.slice(1).map(target=>({source:'center',target})));
assert.ok(Math.max(...Object.values(fan).map(p=>p.y))-Math.min(...Object.values(fan).map(p=>p.y))<=500,'Many backbone branches must use compact surrounding slots rather than a tall column');
const fixed = arrangePresentation(full.nodes.map(n => n.id), full.edges, { 'building-hub': { x: -444,y: 876 } }, ['building-hub']);
assert.deepEqual(fixed['building-hub'], { x: -444,y: 876 });
assert.equal(Object.keys(positions).length, 6);
assert.equal(new Set(Object.values(positions).map(p => `${p.x},${p.y}`)).size, 6);
const thirtyTwo = Array.from({ length: 32 }, (_, i) => ({ id: `b${i}`, name: `Bina ${i}` }));
const thirtyThree = Array.from({ length: 31 }, (_, i) => ({ id: `e${i}`, sourceBuildingId: `b${i}`, destBuildingId: `b${i+1}` })).concat([{ id:'cycle1',sourceBuildingId:'b0',destBuildingId:'b10' },{ id:'cycle2',sourceBuildingId:'b10',destBuildingId:'b31' }]);
const summary = projectPresentation(suggestPresentation(thirtyTwo, thirtyThree), thirtyTwo, thirtyThree, 'summary');
assert.ok(summary.nodes.length < 12, '32 buildings/33 links open as a compact summary');
assert.equal(summary.edges.flatMap(e => e.linkIds).length + summary.internalLinkCount, 33);
console.log('Topology presentation passed: graph suggestions, 32/33 summary, membership validation, aggregation, scope expansion, independent layout and pins. No database writes.');
