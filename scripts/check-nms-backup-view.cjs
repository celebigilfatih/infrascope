/* eslint-disable @typescript-eslint/no-require-imports -- Standalone CommonJS regression runner. */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../lib/nms/backup-view.ts'), 'utf8');
const moduleExports = {};
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: moduleExports, Date, Number });
const { backupCoverage, backupAge, backupDate, backupSize, backupTypeLabel, backupDownloadName } = moduleExports;
const now = Date.parse('2026-10-16T09:00:00Z');
const device = { id: 1, name: 'TEST', lastSuccessAt: '2026-10-15T09:00:00Z', lastPolicySuccessAt: '2026-10-15T09:00:00Z', policy: { enabled: true, staleAfterHours: 48 } };
assert.equal(backupCoverage(device, now).label, 'Yedek güncel');
assert.equal(backupCoverage({ ...device, lastPolicySuccessAt: '2026-10-14T09:00:00Z' }, now).label, 'Yedek gecikmiş');
assert.equal(backupCoverage({ ...device, lastSuccessAt: null, lastPolicySuccessAt: null }, now).label, 'Yedek yok');
assert.equal(backupCoverage({ ...device, lastPolicySuccessAt: null }, now).label, 'Planlanan türde yedek yok');
assert.equal(backupCoverage({ ...device, lastPolicySuccessAt: undefined }, now).tone, 'neutral');
assert.equal(backupCoverage({ ...device, lastPolicySuccessAt: 'invalid' }, now).tone, 'neutral');
assert.equal(backupCoverage({ ...device, lastPolicySuccessAt: '2026-10-17T09:00:00Z' }, now).tone, 'neutral');
assert.equal(backupCoverage({ ...device, policy: null }, now).label, 'Yedek var');
assert.equal(backupCoverage({ ...device, policy: { enabled: false, staleAfterHours: 1 } }, now).attention, false);
assert.equal(backupCoverage({ ...device, policy: { enabled: true, staleAfterHours: NaN } }, now).tone, 'neutral');
assert.equal(backupAge(device.lastSuccessAt, now), '1 gün önce');
assert.match(backupAge('2026-10-17T09:00:00Z', now), /gelecekte/);
assert.equal(backupAge('invalid', now), 'Tarih doğrulanamıyor');
assert.match(backupDate('2026-10-16T09:00:00Z'), /12:00 TSİ$/);
assert.equal(backupDate('invalid'), 'Tarih doğrulanamıyor');
assert.equal(backupSize(0), '0 B');
assert.equal(backupSize(NaN), 'Boyut bilinmiyor');
assert.equal(backupSize(-1), 'Boyut bilinmiyor');
assert.equal(backupSize(1048576), '1 MiB');
assert.equal(backupTypeLabel('unexpected'), 'Bilinmeyen yedek türü');
assert.equal(backupTypeLabel('Startup Config'), 'Başlangıç yapılandırması');
assert.doesNotMatch(backupDownloadName('../../a\r\nb.cfg'), /[\/\r\n]/);
assert.equal(backupDownloadName(''), 'yapilandirma.cfg');
console.log('Backup view checks passed: policy threshold, absent/invalid/future timestamps, disabled schedules, TSİ, size and download filename.');
